#!/usr/bin/env python3
"""Generate the base-ISA Apple-oracle coverage vectors (ARM64OracleCoverageGoldenTests).

This replaces the old ARM64CoverageHarnessTests, which decoded /usr/lib/dyld on every CoreTests run
and counted any non-`unknown` mnemonic as success (a fabricated `str` passed). Here every word has
exact Apple text, or `<unknown>` where Apple rejects it, and the test requires MacScope to agree.

Words: a fixed seed and, for each base-ISA encoding class of differential_sweep.STRUCTURED_CLASSES
(SVE and SME excluded, RX-18), PER_CLASS words that keep the class's fixed bits and randomise the
rest (SIMD/FP gets SIMD_FP words because it is the widest class). Words whose Apple text belongs to
a family the MS-23 ledger §6 lists as out of scope are dropped by mnemonic (OUT_OF_SCOPE), so the
fixture holds only base-ISA and in-scope words. No binary is read and no corpus is decoded.

Ground truth is the local Apple toolchain only, in generic (ELF) syntax: `.inst` words assembled by
`xcrun clang -c -target aarch64-none-elf`, disassembled by
`xcrun llvm-objdump -d --print-imm-hex --mattr=<differential_sweep.MATTR>`. The header records the
tool versions and the exact command.

Output: MacScope/Tests/CoreTests/GoldenFixtures/arm64-coverage-vectors/vectors.tsv
          class  address  word  objdump-text        (`<unknown>` where objdump rejects the word)

usage: Scripts/arm64_golden/generate_arm64_coverage_vectors.py [--check]
"""
from __future__ import annotations

import argparse
import pathlib
import random
import re
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import differential_sweep as ds  # noqa: E402  (MATTR, STRUCTURED_CLASSES, oracle chunk, normalisation)

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "MacScope/Tests/CoreTests/GoldenFixtures/arm64-coverage-vectors/vectors.tsv"
SEED = 2026101223
PER_CLASS = 52
SIMD_FP = 220
EXCLUDED_CLASSES = {"sve", "sme-reserved"}
BASE = ds.DEFAULT_BASE  # 0x100000000, so PC-relative targets never underflow

# Apple mnemonics of families the MS-23 ledger §6 puts out of scope (LSUI, CMPBR, HBC, CPA, LSFE,
# LSE128/RCPC3/LS64, FP8/LUT, GCS, SVE/SME spill-over) or leaves unknown by policy (udf).
OUT_OF_SCOPE = re.compile(
    r"^(ldtp|sttp|ldtnp|sttnp|ldt(add|clr|set)\w*|stt(add|clr|set)\w*|cas\w*t|swp\w*t|cb(gt|ge|hi|hs|eq|ne|lt|lo|le|ls|b\w*|h\w*)|bc\.\w+"
    r"|maddpt|msubpt|addpt|subpt|ldf\w+|stf\w+|ldbf\w+|stbf\w+|ldclrp\w*|ldsetp\w*|swpp\w*|ldiapp|stilp"
    r"|ld64b|st64b\w*|fdot|luti\d|famax|famin|fscale|fmlall\w*|fmlal[bt]\w*|bf1cvt\w*"
    r"|bf2cvt\w*|f1cvt\w*|f2cvt\w*|gcs\w*|udf|tcancel|tstart|ttest|tcommit|sysl?p|tlbip|smstart|smstop"
    r"|fmop4\w*)$"
)


def keep(text: str) -> bool:
    if not ds.llvm_decodes(text):
        return True
    mnemonic, _, operands = text.partition(" ")
    if mnemonic in {"ldapur", "stlur"} and operands[:1] in {"q", "d", "s", "h", "b"}:
        return False  # FEAT_LRCPC3 SIMD forms
    return not OUT_OF_SCOPE.match(mnemonic)


def candidate_words() -> list[tuple[str, int]]:
    rng = random.Random(SEED)
    rows: list[tuple[str, int]] = []
    seen: set[int] = set()
    for name, mask, value in ds.STRUCTURED_CLASSES:
        if name in EXCLUDED_CLASSES:
            continue
        count = SIMD_FP if name == "simd-fp" else PER_CLASS
        produced = 0
        while produced < count:
            word = (rng.getrandbits(32) & ~mask & 0xFFFFFFFF) | value
            if word in seen:
                continue
            seen.add(word)
            rows.append((name, word))
            produced += 1
    return rows


def oracle(words: list[int]) -> list[str]:
    with tempfile.TemporaryDirectory() as tmp:
        texts = ds.llvm_chunk(0, words, BASE, pathlib.Path(tmp))
    out = []
    for text in texts:
        text = ds.normalize(text)
        out.append(text if ds.llvm_decodes(text) else "<unknown>")
    return out


def render() -> str:
    candidates = candidate_words()
    labelled = [(name, word, text) for (name, word), text in zip(candidates, oracle([w for _, w in candidates]))
                if keep(text)]
    # Re-label at the final addresses (PC-relative operands depend on them).
    texts = oracle([w for _, w, _ in labelled])
    versions = ds.tool_versions()
    lines = [
        "# class\taddress\tword\tobjdump",
        "# generated by Scripts/arm64_golden/generate_arm64_coverage_vectors.py "
        f"(seed {SEED}, {PER_CLASS}/class, simd-fp {SIMD_FP}; SVE/SME classes and ledger-§6 out-of-scope mnemonics dropped)",
        f"# oracle: .inst -> xcrun clang -c -target {ds.TARGET}; xcrun llvm-objdump -d --print-imm-hex "
        f"--adjust-vma={BASE:#x} --mattr=<differential_sweep.MATTR>; `<unknown>` = rejected by objdump",
        f"# tools: {versions['clang']}; {versions['llvm-objdump']}",
    ]
    for index, ((name, word, _), text) in enumerate(zip(labelled, texts)):
        lines.append(f"{name}\t{BASE + 4 * index:#x}\t{word:08x}\t{text}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale; rerun without --check", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {sum(1 for line in text.splitlines() if not line.startswith('#'))} rows to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
