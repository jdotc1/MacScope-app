#!/usr/bin/env python3
"""Derive MacScope's BinExport2 schema table from the vendored upstream proto (RX-04).

Input:  ThirdParty/BinExport/binexport2.proto (google/binexport, pinned in VERSION)
Output: MacScope/Services/Export/BinExport2Schema.generated.swift

The vendored schema is consumed by product code: `BinExport2Conformance` checks
every exported field number and wire type against this table before the app
writes a .BinExport file. The table is generated once per pin (the output
records the schema SHA-256), so nothing is rebuilt per build, worktree or CI
run, and no protoc or protobuf runtime is needed. `--check` exits non-zero when
the checked-in output differs from what the vendored schema produces; CI runs
it. Standard library only; Python 3.9+.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path
from typing import Dict, List, Tuple

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "ThirdParty/BinExport/binexport2.proto"
OUTPUT = ROOT / "MacScope/Services/Export/BinExport2Schema.generated.swift"

SCALARS = {
    "int32": "varint", "int64": "varint", "uint32": "varint", "uint64": "varint",
    "sint32": "varint", "sint64": "varint", "bool": "varint",
    "fixed64": "fixed64", "sfixed64": "fixed64", "double": "fixed64",
    "fixed32": "fixed32", "sfixed32": "fixed32", "float": "fixed32",
    "string": "lengthDelimited", "bytes": "lengthDelimited",
}

TOKEN = re.compile(r'"[^"]*"|[A-Za-z_][A-Za-z0-9_.]*|-?\d+|[{}\[\]=;<>,()]')


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def parse(text: str) -> Tuple[Dict[str, List[Tuple[int, str, str, str]]], set]:
    """Returns ({message: [(number, label, name, type)]}, enum full names)."""
    tokens = TOKEN.findall(strip_comments(text))
    messages: Dict[str, List[Tuple[int, str, str, str]]] = {}
    enums: set = set()
    stack: List[Tuple[str, str]] = []  # (kind, full name)
    i = 0

    def skip_statement(index: int) -> int:
        depth = 0
        while index < len(tokens):
            token = tokens[index]
            if token == "{":
                depth += 1
            elif token == "}":
                depth -= 1
                if depth == 0:
                    return index + 1
            elif token == ";" and depth == 0:
                return index + 1
            index += 1
        return index

    while i < len(tokens):
        token = tokens[i]
        scope = stack[-1][1] if stack else ""
        if token in ("message", "enum"):
            name = f"{scope}.{tokens[i + 1]}" if scope else tokens[i + 1]
            if token == "message":
                messages[name] = []
            else:
                enums.add(name)
            stack.append((token, name))
            i += 3  # keyword name {
        elif token == "}":
            stack.pop()
            i += 1
        elif token in ("optional", "repeated", "required") and stack and stack[-1][0] == "message":
            label, kind, name, number = tokens[i], tokens[i + 1], tokens[i + 2], int(tokens[i + 4])
            messages[scope].append((number, label, name, kind))
            i = skip_statement(i)
        else:
            # syntax/option/package/reserved/extensions/enum values
            i = skip_statement(i) if token != ";" else i + 1
    return messages, enums


def resolve(kind: str, scope: str, messages: Dict, enums: set) -> Tuple[str, str]:
    """Returns (wire kind, message type or '')."""
    if kind in SCALARS:
        return SCALARS[kind], ""
    parts = scope.split(".")
    while True:
        candidate = ".".join(parts + [kind]) if parts and parts[0] else kind
        if candidate in messages:
            return "lengthDelimited", candidate
        if candidate in enums:
            return "varint", ""
        if not parts or not parts[0]:
            raise SystemExit(f"unresolved type {kind} in {scope}")
        parts = parts[:-1]


def render(source: bytes) -> str:
    messages, enums = parse(source.decode("utf-8"))
    digest = hashlib.sha256(source).hexdigest()
    lines = [
        "// GENERATED by Scripts/dependencies/generate_binexport2_schema.py. Do not edit.",
        "// Source: ThirdParty/BinExport/binexport2.proto (google/binexport, see VERSION).",
        "",
        "/// Field table of the vendored upstream BinExport2 proto2 schema.",
        "enum BinExport2Schema {",
        f'    static let sourceSHA256 = "{digest}"',
        "",
        "    static let messages: [String: [Int: BinExport2SchemaField]] = [",
    ]
    for message in sorted(messages):
        lines.append(f'        "{message}": [')
        for number, label, name, kind in sorted(messages[message]):
            wire, nested = resolve(kind, message, messages, enums)
            nested_literal = f'"{nested}"' if nested else "nil"
            lines.append(
                f'            {number}: BinExport2SchemaField(name: "{name}", repeated: {str(label == "repeated").lower()}, '
                f"wire: .{wire}, message: {nested_literal}),")
        lines.append("        ],")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the checked-in output is stale")
    arguments = parser.parse_args()
    rendered = render(SOURCE.read_bytes())
    if arguments.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        print("binexport2 schema table current")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
