class AdmissionError(RuntimeError):
    pass


def _fields(value):
    return tuple(getattr(value, key) for key in
                 ('st_dev', 'st_ino', 'st_mode', 'st_nlink', 'st_uid', 'st_gid',
                  'st_size', 'st_mtime_ns', 'st_ctime_ns'))


def _directory_fields(value):
    return tuple(getattr(value, key) for key in
                 ('st_dev', 'st_ino', 'st_mode', 'st_uid', 'st_gid'))


class Lease:
    def __init__(self):
        self.files = {}
        self.directories = {}

    def directory(self, path):
        path = Path(path)
        if not path.is_absolute() or path.resolve(strict=True) != path:
            raise AdmissionError('admission path is not absolute and direct')
        for part in reversed((path, *path.parents)):
            if part in self.directories:
                continue
            before = part.lstat()
            if not stat.S_ISDIR(before.st_mode):
                raise AdmissionError('admission ancestry is not an ordinary directory')
            fd = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
            expected = _directory_fields(before)
            if _directory_fields(os.fstat(fd)) != expected:
                os.close(fd)
                raise AdmissionError('admission ancestry changed while opening')
            self.directories[part] = (fd, expected)
        return self.directories[path][0]

    def file(self, path):
        path = Path(path)
        if path in self.files:
            self.revalidate()
            return
        parent = self.directory(path.parent)
        before = os.stat(path.name, dir_fd=parent, follow_symlinks=False)
        if (not stat.S_ISREG(before.st_mode) or before.st_nlink != 1
                or before.st_uid != os.getuid()):
            raise AdmissionError('admission file must be owner-controlled, ordinary and singly linked')
        fd = os.open(path.name, os.O_RDONLY | os.O_NOFOLLOW, dir_fd=parent)
        expected = _fields(before)
        if _fields(os.fstat(fd)) != expected:
            os.close(fd)
            raise AdmissionError('admission file changed while opening')
        self.files[path] = (fd, expected)

    def revalidate(self):
        for path, (fd, expected) in self.directories.items():
            if (_directory_fields(os.fstat(fd)) != expected
                    or _directory_fields(path.lstat()) != expected):
                raise AdmissionError('admission ancestry changed')
        for path, (fd, expected) in self.files.items():
            if _fields(os.fstat(fd)) != expected or _fields(path.lstat()) != expected:
                raise AdmissionError('admission file changed')

    def close(self):
        for fd, _ in (*self.files.values(), *reversed(tuple(self.directories.values()))):
            os.close(fd)
        self.files.clear()
        self.directories.clear()


def load_helper(root, filename):
    path = root / 'Scripts/qualification' / filename
    name = 'macscope_' + path.stem
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise AdmissionError('admission helper is unavailable')
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def publish(output, payload, lease, revalidate):
    """Publish generated bytes once, retaining the directory and output inode."""
    output = Path(output)
    directory = lease.directory(output.parent)
    temporary = '.' + output.name + '.' + secrets.token_hex(12)
    descriptor = os.open(temporary, os.O_RDWR | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
                         0o600, dir_fd=directory)
    try:
        position = 0
        while position < len(payload):
            written = os.write(descriptor, payload[position:])
            if written <= 0:
                raise AdmissionError('provenance write made no progress')
            position += written
        os.fchmod(descriptor, 0o644)
        os.fsync(descriptor)
        written_fields = _fields(os.fstat(descriptor))
        lease.revalidate()
        revalidate()
        if _fields(os.stat(temporary, dir_fd=directory, follow_symlinks=False)) != written_fields:
            raise AdmissionError('temporary provenance identity changed')
        os.replace(temporary, output.name, src_dir_fd=directory, dst_dir_fd=directory)
        # A rename can change ctime. Retained fd and destination must agree;
        # every other property and the generated size must remain unchanged.
        published = _fields(os.fstat(descriptor))
        if (published[:-1] != written_fields[:-1]
                or _fields(os.stat(output.name, dir_fd=directory, follow_symlinks=False)) != published):
            raise AdmissionError('published provenance identity changed')
        lease.revalidate()
        revalidate()
    finally:
        os.close(descriptor)
        # Preserve a failed temporary object for diagnosis; never unlink a
        # potentially substituted path during error cleanup.


def admit_current(root, receipt_path, receipt, records, read_json):
    """Bind the fresh qualification and its explicitly retained dependencies."""
    retained = Path(os.environ['MACSCOPE_RETAINED_RELEASE_QUALIFICATION_INPUTS'])
    lease = Lease()
    try:
        for path in (receipt_path, root / 'SOURCE_PROVENANCE.json', root / 'SOURCE_FILES.json',
                     receipt_path.parent / 'DEPENDENCY_CACHE_EVENTS.json', retained):
            lease.file(path)
        manifest_helper = load_helper(root, 'qualification_manifest_inheritance.py')
        digests, consulted = manifest_helper.admit_manifests(
            retained, receipt, receipt_path.parent / 'DEPENDENCY_CACHE_EVENTS.json')
        # Hold every receipt, manifest and leaf the inheritance consulted so the
        # digests cannot drift before provenance is published under this lease.
        for path in consulted:
            lease.file(path)
        for key, value in digests.items():
            if receipt.get(key) != value:
                raise AdmissionError('current dependency digest differs from retained admission: ' + key)
        native_helper = load_helper(root, 'native_release_admission.py')
        native = native_helper.admit(root, source_records=records)
        lease.revalidate()
        return {'root': root, 'receipt_path': receipt_path, 'receipt': receipt,
                'run': receipt_path.parent, 'records': records,
                'current_release': True, 'lease': lease,
                'native_helper': native_helper, 'native': native,
                'manifest_helper': manifest_helper,
                # Compatibility data for existing retained dependency consumers.
                # This is a new canonical project, not an operational overlay.
                'overlay': {'retained_release_qualification_inputs': str(retained),
                            'overlay_project_path': str(root / 'MacScope/MacScope.xcodeproj/project.xcproj')}}
    except BaseException:
        lease.close()
        raise


def revalidate(admitted):
    admitted['lease'].revalidate()
    if admitted.get("cache_release"):
        import cache_release_inputs
        cache_release_inputs.revalidate(admitted["cache_inputs"])


def close(admitted):
    admitted['lease'].close()


def retained_release_evidence(admitted, read_json):
    assert admitted is not None
    if "retained_release_evidence" in admitted:
        return admitted["retained_release_evidence"]
    if admitted.get("cache_release"):
        import sys
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import cache_release_inputs
        return cache_release_inputs.retained_evidence(admitted)
    old_path = Path(admitted["overlay"]["retained_release_qualification_inputs"])
    old = read_json(old_path, "retained Release qualification inputs")
    # This function supplies only Ghostty evidence. A fresh Release has already
    # admitted its native package independently; it need not equal the older
    # Release's SLEIGH package. Keep the legacy overlay's original constraint.
    keys = ("ghostty_surface_manifest_sha256",)
    if not admitted.get("current_release"):
        keys += ("sleigh_materialization_manifest_sha256",)
    for key in keys:
        if old.get(key) != admitted["receipt"].get(key):
            raise AdmissionError("retained Release dependency admission differs: " + key)
    provenance = old_path.parent / "DerivedData/Build/Products/Release/MacScope.app/Contents/Resources/MacScopeBuildProvenance.json"
    value = read_json(provenance, "retained Release provenance")
    if (value.get("configuration") != "Release"
            or value.get("ghostty_surface_source_manifest_sha256") != old.get("ghostty_surface_manifest_sha256")):
        raise AdmissionError("retained Release Ghostty dependency admission differs")
    admitted["retained_release_evidence"] = value
    return value

