"""Descriptor-held publication for one newly built Release using admitted inputs.

Accepted source/dependency/native computation digests are inherited. New signed
worker evidence is captured by its producer once; publication holds metadata
continuity instead of reading that evidence again.
"""
from __future__ import annotations

