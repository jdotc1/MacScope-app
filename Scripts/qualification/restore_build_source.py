#!/usr/bin/env python3
"""Remove only MacScope's validated, generated build-source scaffolding."""

from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import shutil
import stat
import sys
from typing import Iterable


MAX_PROJECT_FILES = 1_000
MAX_PROJECT_BYTES = 64 * 1024 * 1024
MAX_XCCONFIG_BYTES = 64 * 1024
GENERATED_PROJECT_FILES = {
    ".macscope-project-generation.sha256",
    "project.xcproj",
    "project.xcworkspace/contents.xcworkspacedata",
    "xcshareddata/xcschemes/MacScopeApp.xcscheme",
    # #378 split the hosted tests into per-bundle schemes.
    "xcshareddata/xcschemes/CoreTests.xcscheme",
    "xcshareddata/xcschemes/Phase2Tests.xcscheme",
    "xcshareddata/xcschemes/MacScopeInstalledAppUITests.xcscheme",
}
GENERATED_PROJECT_DIRECTORIES = {
    "project.xcworkspace",
    "project.xcworkspace/xcshareddata",
    "project.xcworkspace/xcshareddata/swiftpm",
    "project.xcworkspace/xcshareddata/swiftpm/configuration",
    "xcshareddata",
    "xcshareddata/xcschemes",
}


class BuildSourceRestoreError(RuntimeError):
    """The generated build-source surface was absent, unsafe, or unexpected."""


def _canonical_directory(path: Path, label: str) -> Path:
    if not path.is_absolute():
        raise BuildSourceRestoreError(f"{label} must be an absolute canonical path")
    try:
        resolved = path.resolve(strict=True)
        metadata = path.lstat()
    except OSError as error:
        raise BuildSourceRestoreError(f"{label} could not be inspected") from error
    if resolved != path or stat.S_ISLNK(metadata.st_mode) or not stat.S_ISDIR(metadata.st_mode):
        raise BuildSourceRestoreError(f"{label} must be an ordinary directory")
    return resolved


def _read_stable_regular_file(path: Path, label: str) -> bytes | None:
    try:
        metadata = path.lstat()
    except FileNotFoundError:
        return None
    except OSError as error:
        raise BuildSourceRestoreError(f"{label} could not be inspected") from error
    if (
        not stat.S_ISREG(metadata.st_mode)
        or metadata.st_nlink != 1
        or stat.S_IMODE(metadata.st_mode) != 0o600
    ):
        raise BuildSourceRestoreError(
            f"{label} must be one mode-0600 ordinary single-link file"
        )
    if metadata.st_size <= 0 or metadata.st_size > MAX_XCCONFIG_BYTES:
        raise BuildSourceRestoreError(f"{label} exceeds its content bound")
    descriptor = -1
    try:
        descriptor = os.open(
            path,
            os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_CLOEXEC", 0),
        )
        opened = os.fstat(descriptor)
        payload = os.read(descriptor, MAX_XCCONFIG_BYTES + 1)
        after_descriptor = os.fstat(descriptor)
    except OSError as error:
        raise BuildSourceRestoreError(f"{label} could not be read safely") from error
    finally:
        if descriptor >= 0:
            os.close(descriptor)
    after = path.lstat()
    stable = ("st_dev", "st_ino", "st_mode", "st_nlink", "st_size", "st_mtime_ns", "st_ctime_ns")
    if len(payload) != metadata.st_size or any(
        getattr(metadata, field) != getattr(observed, field)
        for observed in (opened, after_descriptor, after)
        for field in stable
    ):
        raise BuildSourceRestoreError(f"{label} changed while inspected")
    return payload


def _expected_xcconfig(
    source: Path,
    machokit_root: Path,
    dependency_cache_root: Path,
    pattern_adapter_root: Path | None,
) -> bytes:
    run = source.parent
    ghostty_surface_work_root = run / "dependencies/ghostty-surface"
    ghostty_surface_source_dir = ghostty_surface_work_root / "GhosttySurface"
    ghostty_surface_artifact_root = (
        ghostty_surface_source_dir / "macos/GhosttyKit.xcframework"
    )
    sleigh_source_build_root = (
        run / "dependencies/sleigh-native-source/SleighNativeSource"
    )
    sleigh_materialization_root = sleigh_source_build_root / "materialization"
    framework = ghostty_surface_artifact_root / "macos-arm64/libghostty-internal.a"
    component = source / "ThirdParty/SleighNative"
    return (
        "// Generated by Scripts/bootstrap.sh. Untracked and machine-local — do not commit.\n"
        "// Regenerate by re-running bootstrap; edit DependencyRoots.xcconfig for anything\n"
        "// that should be shared.\n"
        f"MACSCOPE_GHOSTTY_SURFACE_WORK_ROOT = {ghostty_surface_work_root}\n"
        f"MACSCOPE_GHOSTTY_SURFACE_SOURCE_DIR = {ghostty_surface_source_dir}\n"
        f"MACSCOPE_GHOSTTY_SURFACE_ARTIFACT_ROOT = {ghostty_surface_artifact_root}\n"
        f"MACSCOPE_GHOSTTY_SURFACE_FRAMEWORK = {framework}\n"
        "MACSCOPE_GHOSTTY_SURFACE_ENABLED = MACSCOPE_FULL_GHOSTTY_SURFACE\n"
        f"MACSCOPE_SLEIGH_COMPONENT_ROOT = {component}\n"
        f"MACSCOPE_SLEIGH_SOURCE_BUILD_ROOT = {sleigh_source_build_root}\n"
        f"MACSCOPE_SLEIGH_MATERIALIZATION_ROOT = {sleigh_materialization_root}\n"
        f"MACSCOPE_MACHOKIT_MATERIALIZATION_ROOT = {machokit_root}\n"
        f"MACSCOPE_PARSER_ENGINE_CACHE_ROOT = {dependency_cache_root}\n"
        f"MACSCOPE_PATTERN_ADAPTER_ROOT = {pattern_adapter_root or ''}\n"
    ).encode("utf-8")


def _generated_project_identity(
    path: Path,
    *,
    require_complete: bool,
) -> str | None:
    if not shutil.rmtree.avoids_symlink_attacks:
        raise BuildSourceRestoreError(
            "generated Xcode project cleanup requires symlink-resistant rmtree"
        )
    try:
        root_metadata = path.lstat()
    except FileNotFoundError:
        return None
    except OSError as error:
        raise BuildSourceRestoreError("generated Xcode project could not be inspected") from error
    if stat.S_ISLNK(root_metadata.st_mode) or not stat.S_ISDIR(root_metadata.st_mode):
        raise BuildSourceRestoreError("generated Xcode project must be an ordinary directory")

    observed_files: dict[str, Path] = {}
    total_bytes = 0
    for candidate in path.rglob("*"):
        try:
            metadata = candidate.lstat()
        except OSError as error:
            raise BuildSourceRestoreError(
                "generated Xcode project changed while inspected"
            ) from error
        if stat.S_ISLNK(metadata.st_mode):
            raise BuildSourceRestoreError("generated Xcode project contains a symlink")
        if stat.S_ISDIR(metadata.st_mode):
            relative = candidate.relative_to(path).as_posix()
            if relative not in GENERATED_PROJECT_DIRECTORIES:
                raise BuildSourceRestoreError(
                    "generated Xcode project contains an unexpected directory"
                )
            continue
        if not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1:
            raise BuildSourceRestoreError(
                "generated Xcode project contains an unsafe entry"
            )
        relative = candidate.relative_to(path).as_posix()
        if relative not in GENERATED_PROJECT_FILES:
            raise BuildSourceRestoreError(
                "generated Xcode project contains an unexpected file"
            )
        observed_files[relative] = candidate
        total_bytes += metadata.st_size
        if len(observed_files) > MAX_PROJECT_FILES or total_bytes > MAX_PROJECT_BYTES:
            raise BuildSourceRestoreError("generated Xcode project exceeds its cleanup bound")
    if require_complete and set(observed_files) != GENERATED_PROJECT_FILES:
        raise BuildSourceRestoreError(
            "generated Xcode project is incomplete and cannot be bound"
        )

    digest = hashlib.sha256()
    for relative, candidate in sorted(observed_files.items()):
        before = candidate.lstat()
        if not stat.S_ISREG(before.st_mode) or before.st_nlink != 1:
            raise BuildSourceRestoreError(
                f"generated Xcode project file {relative} became unsafe"
            )
        try:
            descriptor = os.open(
                candidate,
                os.O_RDONLY
                | getattr(os, "O_NOFOLLOW", 0)
                | getattr(os, "O_CLOEXEC", 0),
            )
            with os.fdopen(descriptor, "rb") as stream:
                payload = stream.read(MAX_PROJECT_BYTES + 1)
                opened = os.fstat(stream.fileno())
            after = candidate.lstat()
        except OSError as error:
            raise BuildSourceRestoreError(
                f"generated Xcode project file {relative} could not be read safely"
            ) from error
        stable = (
            "st_dev",
            "st_ino",
            "st_mode",
            "st_nlink",
            "st_size",
            "st_mtime_ns",
            "st_ctime_ns",
        )
        if len(payload) != before.st_size or any(
            getattr(before, field) != getattr(observed, field)
            for observed in (opened, after)
            for field in stable
        ):
            raise BuildSourceRestoreError(
                f"generated Xcode project file {relative} changed while inspected"
            )
        name = relative.encode("utf-8")
        digest.update(len(name).to_bytes(4, "big"))
        digest.update(name)
        digest.update(len(payload).to_bytes(8, "big"))
        digest.update(payload)
    return digest.hexdigest()


def _validated_context(
    build_source: Path,
    machokit_root: Path,
) -> tuple[Path, Path, Path]:
    source = _canonical_directory(build_source.expanduser(), "build source root")
    machokit = _canonical_directory(machokit_root.expanduser(), "private MachOKit root")
    run = source.parent
    if (
        source.name != "source"
        or machokit.name != "private-machokit-input"
        or machokit.parent != run
        or not run.name.startswith("run.")
        or run.parent.name != "runs"
    ):
        raise BuildSourceRestoreError(
            "build source and MachOKit roots do not have the run-owned layout"
        )

    macscope = source / "MacScope"
    _canonical_directory(macscope, "MacScope source directory")
    project_yml = macscope / "project.yml"
    try:
        project_metadata = project_yml.lstat()
    except OSError as error:
        raise BuildSourceRestoreError("MacScope project.yml could not be inspected") from error
    if not stat.S_ISREG(project_metadata.st_mode) or project_metadata.st_nlink != 1:
        raise BuildSourceRestoreError("MacScope project.yml must be an ordinary single-link file")
    return source, machokit, macscope


def generated_project_identity(
    build_source: Path,
    machokit_root: Path,
) -> str:
    _, _, macscope = _validated_context(build_source, machokit_root)
    project = macscope / "MacScope.xcodeproj"
    identity = _generated_project_identity(project, require_complete=True)
    if identity is None:
        raise BuildSourceRestoreError("generated Xcode project is missing and cannot be bound")
    return identity


def restore_build_source(
    build_source: Path,
    machokit_root: Path,
    dependency_cache_root: Path,
    *,
    expected_project_identity: str | None = None,
    pattern_adapter_root: Path | None = None,
) -> None:
    source, machokit, macscope = _validated_context(build_source, machokit_root)
    # Parser archives live in the admitted shared cache, not under run.NAME.
    # Require its canonical identity without walking or re-verifying its bytes.
    cache = _canonical_directory(dependency_cache_root.expanduser(), "dependency cache root")
    # Bind the optional, already-admitted adapter identity explicitly. Never
    # infer it from the generated file that this operation is validating.
    pattern_adapter = None
    if pattern_adapter_root is not None:
        pattern_adapter = _canonical_directory(pattern_adapter_root, "pattern adapter root")
        if any(token in str(pattern_adapter) for token in ('"', '$', '//', '\\', '\n', '\r')):
            raise BuildSourceRestoreError("pattern adapter root is not representable in an xcconfig")
    local_packages = macscope / "LocalPackages"
    has_local_packages = False
    try:
        link_metadata = local_packages.lstat()
    except FileNotFoundError:
        pass
    except OSError as error:
        raise BuildSourceRestoreError("LocalPackages could not be inspected") from error
    else:
        if not stat.S_ISLNK(link_metadata.st_mode):
            raise BuildSourceRestoreError("LocalPackages must be the generated symlink")
        try:
            payload = os.readlink(local_packages)
            target = local_packages.resolve(strict=True)
        except OSError as error:
            raise BuildSourceRestoreError("LocalPackages target is unavailable") from error
        if payload != str(machokit) or target != machokit:
            raise BuildSourceRestoreError(
                "LocalPackages does not target the run-owned MachOKit root"
            )
        has_local_packages = True

    local_xcconfig = macscope / "DependencyRoots.local.xcconfig"
    observed_xcconfig = _read_stable_regular_file(
        local_xcconfig,
        "generated dependency-roots xcconfig",
    )
    has_local_xcconfig = observed_xcconfig is not None
    if has_local_xcconfig and observed_xcconfig != _expected_xcconfig(
        source,
        machokit,
        cache,
        pattern_adapter,
    ):
        raise BuildSourceRestoreError(
            "generated dependency-roots xcconfig differs from canonical run roots"
        )
    project = macscope / "MacScope.xcodeproj"
    project_identity = _generated_project_identity(project, require_complete=False)
    if expected_project_identity is not None and (
        len(expected_project_identity) != 64
        or any(
            character not in "0123456789abcdef"
            for character in expected_project_identity
        )
    ):
        raise BuildSourceRestoreError("expected generated-project identity is malformed")
    if expected_project_identity is not None and project_identity != expected_project_identity:
        raise BuildSourceRestoreError(
            "generated Xcode project differs from its bound pre-Xcode identity"
        )

    # Mutate only after every present scaffold has passed its safety contract.
    if has_local_packages:
        local_packages.unlink()
    if has_local_xcconfig:
        local_xcconfig.unlink()
    if project_identity is not None:
        # Narrow the validation-to-deletion window and require the runtime's
        # descriptor-based rmtree implementation. A same-user swap to a
        # symlink is never followed; an ordinary replacement must retain the
        # same exact byte identity immediately before removal.
        final_identity = _generated_project_identity(project, require_complete=False)
        if final_identity is None:
            raise BuildSourceRestoreError("generated Xcode project disappeared before cleanup")
        if (
            expected_project_identity is not None
            and final_identity != expected_project_identity
        ):
            raise BuildSourceRestoreError(
                "generated Xcode project differs from its bound pre-Xcode identity"
            )
        shutil.rmtree(project)


def parse_arguments(argv: Iterable[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--operation",
        choices=("restore", "identity"),
        default="restore",
    )
    parser.add_argument("--build-source-root", required=True, type=Path)
    parser.add_argument("--machokit-root", required=True, type=Path)
    parser.add_argument("--dependency-cache-root", required=True, type=Path)
    parser.add_argument("--expected-project-identity")
    parser.add_argument("--pattern-adapter-root", type=Path)
    return parser.parse_args(argv)


def main(argv: Iterable[str] | None = None) -> int:
    arguments = parse_arguments(argv)
    try:
        if arguments.operation == "identity":
            if arguments.expected_project_identity is not None:
                raise BuildSourceRestoreError(
                    "--expected-project-identity is valid only for restore"
                )
            print(
                generated_project_identity(
                    arguments.build_source_root,
                    arguments.machokit_root,
                )
            )
        else:
            restore_build_source(
                arguments.build_source_root,
                arguments.machokit_root,
                arguments.dependency_cache_root,
                expected_project_identity=arguments.expected_project_identity,
                pattern_adapter_root=arguments.pattern_adapter_root,
            )
    except (BuildSourceRestoreError, OSError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
