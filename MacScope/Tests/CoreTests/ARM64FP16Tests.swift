    func testExistingScalarFP16Paths() {
        XCTAssertEqual(text(0x1ee22820), "fadd h0, h1, h2")
        XCTAssertEqual(text(0x1ee0c020), "fabs h0, h1")
        XCTAssertEqual(text(0x1ee24020), "fcvt s0, h1")
        XCTAssertEqual(text(0x1e23c020), "fcvt h0, s1")
        XCTAssertEqual(text(0x1ee02028), "fcmp h1, #0.0")
        XCTAssertEqual(text(0x1fc20c20), "fmadd h0, h1, h2, h3")
        XCTAssertEqual(text(0x1ee20420), "fccmp h1, h2, #0, eq")
        XCTAssertEqual(text(0x1ee21c20), "fcsel h0, h1, h2, ne")
