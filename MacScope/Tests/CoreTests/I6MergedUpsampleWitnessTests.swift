    private func assertComplete(_ witness: Witness) throws {
        let characters = Array(witness.hex.filter { !$0.isWhitespace })
        XCTAssertEqual(characters.count % 8, 0, witness.name)
        let bytes = try Data(stride(from: 0, to: characters.count, by: 2).map {
            try XCTUnwrap(UInt8(String(characters[$0...$0 + 1]), radix: 16), witness.name)
        })
        let rows = ARM64Decoder().decode(bytes, baseAddress: witness.address,
            maxInstructionCount: bytes.count / 4).map {
            InstructionRow(address: $0.address, bytes: $0.byteText, mnemonic: $0.mnemonic,
                operands: $0.operands, hasBreakpoint: false, comment: $0.comment)
        }
        XCTAssertEqual(rows.count, bytes.count / 4, witness.name)
        let tables = JumpTableResolver().resolve(instructions: rows, readBytes: { base, count in
            guard base >= witness.tableBase,
                  base - witness.tableBase < UInt64(witness.entries.count), count == 1 else { return nil }
            return Data([witness.entries[Int(base - witness.tableBase)]])
        }, codeRange: .init(lowerBound: witness.address,
                           upperBound: witness.address + UInt64(bytes.count)))
        let dispatch = try XCTUnwrap(rows.first { $0.mnemonic == "br" }, witness.name)
        XCTAssertEqual(tables[dispatch.address],
            witness.entries.map { dispatch.address + 4 + UInt64($0) * 4 }, witness.name)
        let function = MacIRBuilder().buildFunction(name: witness.name, startAddress: witness.address,
            jumpTables: tables, instructions: rows)
        XCTAssertEqual(Set(function.instructions.map(\.source.address)), Set(rows.map(\.address)),
            "\(witness.name): every original row must retain an effect, including stores and returns")
        let unknown = function.instructions.filter {
            if case .unknown = $0.operation { return true }
            return false
        }
        XCTAssertEqual(unknown.count, 0, "\(witness.name): \(unknown.map { $0.source })")
        let selectedStores = rows.filter {
            ["st3", "st4"].contains($0.mnemonic) && $0.operands.contains("}[")
        }
        XCTAssertEqual(selectedStores.count, witness.name.contains("h2v2") ? 28 : 14, witness.name)
        for row in selectedStores {
            let structureCount = row.mnemonic == "st3" ? 3 : 4
            let effects = function.instructions.filter { $0.source.address == row.address }
            XCTAssertEqual(effects.count, structureCount, witness.name)
            XCTAssertTrue(effects.allSatisfy { $0.neonStructureLaneMemory != nil },
                          "\(witness.name): selected store at \(row.address)")
            let frame = try XCTUnwrap(effects.first?.neonStructureLaneMemory?.frame, witness.name)
            XCTAssertEqual(frame.byteCount, structureCount, witness.name)
            XCTAssertEqual(frame.structureCount, structureCount, witness.name)
            XCTAssertEqual(frame.elementBytes, 1, witness.name)
            XCTAssertEqual(frame.effect, .store, witness.name)
            XCTAssertTrue(frame.destinations.isEmpty, witness.name)
            XCTAssertNil(frame.baseDestination, witness.name)
        }
        XCTAssertEqual(function.instructions.filter {
            if case .returnValue = $0.operation { return true }
            return false
        }.count, 2, witness.name)
        let output = PseudocodePrinter().print(function: function).text
        XCTAssertEqual(output.components(separatedBy: "\n").filter { $0.contains("__unknown") }.count,
                       0, witness.name)
    }

